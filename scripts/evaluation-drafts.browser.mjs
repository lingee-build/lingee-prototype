// 先启动 bun run dev；与 report-preview.browser.mjs 使用相同的 Playwright 环境变量。
import assert from 'node:assert/strict'
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright')
const browser = await chromium.launch({ headless: true, channel: process.env.PLAYWRIGHT_BROWSER_CHANNEL })
try {
  for (const kind of ['skill', 'agent']) {
    const page = await browser.newPage()
    const errors = []
    page.on('pageerror', e => errors.push(e.message))
    await page.goto(`${process.env.REPORT_TEST_URL || 'http://127.0.0.1:5180'}/dev/${kind}`)
    const id = await page.evaluate(async kind => {
      const { useAuth } = await import('/src/stores/auth.ts')
      const { accounts, PASSWORD } = await import('/src/mock/fixtures/accounts.ts')
      useAuth.getState().login(accounts[0].account, PASSWORD)
      const { devStore } = await import('/src/mock/dev-store.ts')
      return (kind === 'skill' ? devStore.skills : devStore.agents)[0].id
    }, kind)
    await page.goto(`http://127.0.0.1:5180/dev/${kind}/${id}/evaluation`)
    const editor = page.locator('[contenteditable=true]').last()
    await editor.fill('尚未发送的用例需求 XYZ')
    await page.locator('.eval-native-session input[type=file]').first().setInputFiles({ name: 'draft.txt', mimeType: 'text/plain', buffer: Buffer.from('附件草稿') })
    await page.getByText(/^评测报告 \(/).click()
    await page.waitForFunction(() => new URLSearchParams(location.search).get('tab') === 'reports')
    await page.waitForTimeout(100)
    assert.equal(await page.locator('.eval-workbench').getAttribute('data-chat-open'), 'true', '切换报告列表保持对话展开')
    await editor.fill('列表中的独立草稿')
    await editor.press('Enter')
    await page.getByText('请先在右侧选择一次评测运行或报告。',{exact:true}).waitFor()
    assert.equal(await editor.innerText().then(text => text.replace(/^evaluation-builder\s*/, '')), '列表中的独立草稿', '发送失败保留文字')
    await page.getByText(/^评测用例 \(/).click()
    await page.waitForFunction(() => !new URLSearchParams(location.search).has('tab'))
    await page.waitForTimeout(100)
    assert.equal(await editor.innerText().then(text => text.replace(/^evaluation-builder\s*/, '')), '尚未发送的用例需求 XYZ')
    assert.equal(await page.locator('[data-component=prompt-attachments]').innerText().then(t => t.includes('draft.txt')), true)
    await page.locator('.eval-panel-header button[aria-expanded]').click()
    await page.locator('.eval-panel-header button[aria-expanded]').click()
    assert.equal(await editor.innerText().then(text => text.replace(/^evaluation-builder\s*/, '')), '尚未发送的用例需求 XYZ')
    await editor.fill('')
    await page.getByText(/^评测报告 \(/).click()
    await page.waitForFunction(() => new URLSearchParams(location.search).get('tab') === 'reports')
    await page.waitForTimeout(100)
    assert.equal(await editor.innerText().then(text => text.replace(/^evaluation-builder\s*/, '')), '列表中的独立草稿')
    await page.getByText(/^评测用例 \(/).click()
    await page.waitForFunction(() => !new URLSearchParams(location.search).has('tab'))
    await page.waitForTimeout(100)
    assert.equal(await editor.innerText().then(text => text.replace(/^evaluation-builder\s*/, '')), '', '主动清空后不重新预填')
    await page.evaluate(async ({kind,id}) => {
      const {useEvaluation}=await import('/src/services/evaluation.ts')
      const started=Date.now()-2000
      useEvaluation.setState(s=>({runs:{...s.runs,[`${kind}:${id}`]:[1,2].map(n=>({id:`draft-run-${n}`,code:`ER-000${n}`,name:'草稿隔离测试',started,ended:started+1000,status:'completed',results:[],snapshot:{version:'v1',capturedAt:started,cases:[]}}))}}))
    }, {kind,id})
    await page.getByText(/^评测报告 \(/).click()
    await page.waitForFunction(() => new URLSearchParams(location.search).get('tab') === 'reports')
    await page.waitForTimeout(100)
    await page.getByText('ER-0001',{exact:true}).click()
    await page.waitForFunction(() => new URLSearchParams(location.search).get('run') === 'draft-run-1')
    await page.waitForTimeout(100)
    assert.equal(await page.locator('.eval-workbench').getAttribute('data-chat-open'), 'true', '已结束报告详情默认展开会话')
    await editor.fill('报告一草稿')
    await page.getByRole('button',{name:'返回报告列表',exact:true}).click()
    await page.waitForFunction(() => !new URLSearchParams(location.search).has('run'))
    await page.getByText('ER-0002',{exact:true}).click()
    await page.waitForFunction(() => new URLSearchParams(location.search).get('run') === 'draft-run-2')
    await page.waitForTimeout(100)
    assert.equal(await editor.innerText().then(text => text.replace(/^evaluation-builder\s*/, '')), '')
    await editor.fill('报告二草稿')
    await page.getByRole('button',{name:'返回报告列表',exact:true}).click()
    await page.waitForFunction(() => !new URLSearchParams(location.search).has('run'))
    await page.getByText('ER-0001',{exact:true}).click()
    await page.waitForFunction(() => new URLSearchParams(location.search).get('run') === 'draft-run-1')
    await page.waitForTimeout(100)
    assert.equal(await editor.innerText().then(text => text.replace(/^evaluation-builder\s*/, '')), '报告一草稿')
    await page.getByText(/^评测用例 \(/).click()
    await page.waitForFunction(() => !new URLSearchParams(location.search).has('tab'))
    await page.waitForTimeout(100)
    await editor.fill('请介绍评测功能')
    await editor.press('Enter')
    await page.waitForFunction(() => (document.querySelector('[contenteditable=true]')?.textContent || '').replace(/^evaluation-builder\s*/, '') === '')
    assert.equal(await page.locator('[data-component=prompt-attachments]').count(), 0, '发送成功清空附件')
    await page.getByText(/^评测报告 \(/).click()
    await page.waitForFunction(() => new URLSearchParams(location.search).get('tab') === 'reports')
    await page.getByText(/^评测用例 \(/).click()
    await page.waitForFunction(() => !new URLSearchParams(location.search).has('tab'))
    await page.waitForTimeout(100)
    assert.equal(await editor.innerText().then(text => text.replace(/^evaluation-builder\s*/, '')), '', '已发送草稿不会复活')
    assert.deepEqual(errors, [])
    console.log(`PASS ${kind}：视图文字与附件保留、收起展开、清空不预填、列表与报告草稿隔离、已结束报告默认展开`)
    await page.close()
  }
} finally { await browser.close() }
